export function toSessionUser(account, emailFallback) {
  if (!account) {
    return {
      id: 'ADM-1001',
      authenticated: true,
      email: emailFallback,
      name: 'Admin',
      role: ROLES.SUPER_ADMIN,
      initials: 'AD',
      city: 'Ahmedabad',
      financeAccess: true,
      payoutApprove: true,
      modules: [...MODULE_KEYS],
      status: 'Active',
    };
  }
  const name = account.name || 'Admin';
  return {
    id: account.id,
    authenticated: true,
    email: account.email || emailFallback,
    name,
    role: account.role,
    initials: account.initials || name.split(' ').filter(Boolean).slice(0, 2).map((part) => part[0]).join('').toUpperCase(),
    city: account.city || 'Ahmedabad',
    financeAccess: account.financeAccess !== false && account.role !== ROLES.SUB_ADMIN ? account.financeAccess !== false : Boolean(account.financeAccess),
    payoutApprove: Boolean(account.payoutApprove),
    modules: Array.isArray(account.modules) ? account.modules : defaultModulesForRole(account.role),
    status: account.status || 'Active',
  };
}
